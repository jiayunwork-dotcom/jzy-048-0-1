'use strict';

/**
 * WGS84 椭球常数与横轴墨卡托投影级数系数。
 *
 * 本实现选用 **Krüger n 级数（6 阶）**，即
 *   C. F. F. Karney, "Transverse Mercator with an accuracy of a few
 *   nanometers", Journal of Geodesy 85(8): 475–485 (2011)
 * 给出的展开式（与 EPSG Guidance Note 7-2 方法 9807 同族），
 * 在 UTM 带内正/反算精度均优于 1 微米（纳米量级），
 * 而非低精度的球面近似。
 *
 * 该模块只做纯计算，不保存任何请求状态，天然满足并发无串扰。
 */

// ---- WGS84 基本常数 -------------------------------------------------------
const a = 6378137.0;                 // 长半轴 (m)
const f = 1 / 298.257223563;         // 扁率
const e2 = f * (2 - f);              // 第一偏心率平方 e^2
const e = Math.sqrt(e2);             // 第一偏心率
const n = f / (2 - f);               // 第三扁率 n —— Krüger 级数展开参数

// ---- 投影固定参数（按需求钉死） -------------------------------------------
const K0 = 0.9996;                   // 中央经线比例因子
const FALSE_EASTING = 500000;        // 假东偏移 (m)
const FALSE_NORTHING = 10000000;     // 南半球假北偏移 (m)

// ---- 子午线 rectifying 半径 A（Karney 式 (3)） -----------------------------
const n2 = n * n;
const n3 = n2 * n;
const n4 = n3 * n;
const n5 = n4 * n;
const n6 = n5 * n;

const A = (a / (1 + n)) * (1 + n2 / 4 + n4 / 64 + n6 / 256);

// ---- 正算级数系数 alpha_j（Karney 式 (5)），下标 1..6 ----------------------
const ALPHA = [
  0,
  (1 / 2) * n - (2 / 3) * n2 + (5 / 16) * n3 + (41 / 180) * n4 -
    (127 / 288) * n5 + (7891 / 37800) * n6,
  (13 / 48) * n2 - (3 / 5) * n3 + (557 / 1440) * n4 + (281 / 630) * n5 -
    (1983433 / 1935360) * n6,
  (61 / 240) * n3 - (103 / 140) * n4 + (15061 / 26880) * n5 +
    (167603 / 181440) * n6,
  (49561 / 161280) * n4 - (179 / 168) * n5 + (6601661 / 7257600) * n6,
  (34729 / 80640) * n5 - (3418889 / 1995840) * n6,
  (212378941 / 319334400) * n6,
];

// ---- 反算级数系数 beta_j（Karney 式 (7)），下标 1..6 -----------------------
const BETA = [
  0,
  (1 / 2) * n - (2 / 3) * n2 + (37 / 96) * n3 - (1 / 360) * n4 -
    (81 / 512) * n5 + (96199 / 604800) * n6,
  (1 / 48) * n2 + (1 / 15) * n3 - (437 / 1440) * n4 + (46 / 105) * n5 -
    (1118711 / 3870720) * n6,
  (17 / 480) * n3 - (37 / 840) * n4 - (209 / 4480) * n5 +
    (5569 / 90720) * n6,
  (4397 / 161280) * n4 - (11 / 504) * n5 - (830251 / 7257600) * n6,
  (4583 / 161280) * n5 - (108847 / 3991680) * n6,
  (20648693 / 638668800) * n6,
];

// ---- 等角纬度 -> 大地纬度 系数 delta_j（Karney 式 (19)），下标 1..6 --------
const DELTA = [
  0,
  2 * n - (2 / 3) * n2 - 2 * n3 + (116 / 45) * n4 + (26 / 45) * n5 -
    (2854 / 675) * n6,
  (7 / 3) * n2 - (8 / 5) * n3 - (227 / 45) * n4 + (2704 / 315) * n5 +
    (2323 / 945) * n6,
  (56 / 15) * n3 - (136 / 35) * n4 - (1262 / 105) * n5 +
    (73814 / 2835) * n6,
  (4279 / 630) * n4 - (332 / 35) * n5 - (399572 / 14175) * n6,
  (4174 / 315) * n5 - (144838 / 6237) * n6,
  (601676 / 22275) * n6,
];

module.exports = {
  a,
  f,
  e2,
  e,
  n,
  A,
  ALPHA,
  BETA,
  DELTA,
  SERIES_ORDER: 6,
  K0,
  FALSE_EASTING,
  FALSE_NORTHING,
};
